create table accounts (
 id bigint generated by default as identity primary key,
 username varchar(40) not null unique,
 password_hash varchar(255) not null,
 name varchar(120) not null,
 role varchar(16) not null check (role in ('CLIENTE','EMPRESA','BANCO')),
 rg varchar(20), cpf varchar(11) unique, address varchar(250), profession varchar(100)
);
create table employers (
 id bigint generated by default as identity primary key,
 account_id bigint not null references accounts(id),
 name varchar(120) not null, income numeric(12,2) not null check (income >= 0)
);
create table vehicles (
 id bigint generated by default as identity primary key,
 registration varchar(40) not null unique,
 year integer not null check (year >= 1900), brand varchar(60) not null, model varchar(80) not null,
 plate varchar(7) not null unique, daily_rate numeric(12,2) not null check (daily_rate > 0),
 owner_id bigint not null references accounts(id), company_id bigint not null references accounts(id),
 version bigint not null default 0
);
create table rentals (
 id bigint generated by default as identity primary key,
 client_id bigint not null references accounts(id), vehicle_id bigint not null references vehicles(id),
 company_id bigint not null references accounts(id), bank_id bigint references accounts(id),
 start_date date not null, end_date date not null check (end_date > start_date),
 total numeric(12,2) not null check (total > 0), credit_amount numeric(12,2), installments integer,
 status varchar(24) not null check (status in ('EM_ANALISE','AGUARDANDO_BANCO','APROVADO','REJEITADO','CANCELADO','CONTRATADO')),
 created_at timestamp with time zone not null,
 version bigint not null default 0,
 check ((bank_id is null and credit_amount is null and installments is null) or
        (bank_id is not null and credit_amount > 0 and credit_amount <= total and installments between 1 and 60))
);
create index idx_rental_availability on rentals(vehicle_id, start_date, end_date, status);
create index idx_rental_client on rentals(client_id);
create table contracts (
 id bigint generated by default as identity primary key,
 rental_id bigint not null unique references rentals(id),
 accepted_at timestamp with time zone not null,
 terms text not null
);
create table rental_events (
 id bigint generated by default as identity primary key,
 rental_id bigint not null references rentals(id), actor_id bigint not null references accounts(id),
 actor_name varchar(120) not null, action varchar(60) not null, note varchar(4000) not null,
 created_at timestamp with time zone not null
);
