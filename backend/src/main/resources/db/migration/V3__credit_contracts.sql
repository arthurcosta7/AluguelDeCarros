create table credit_contracts (
 id bigint generated by default as identity primary key,
 contract_id bigint not null unique references contracts(id),
 bank_id bigint not null references accounts(id),
 amount numeric(12,2) not null check (amount > 0),
 installments integer not null check (installments between 1 and 60),
 accepted_at timestamp with time zone not null,
 terms text not null
);
create index idx_credit_contract_bank on credit_contracts(bank_id);
-- Documentos antigos preservam o texto aceito, sem reconstruir dados pessoais atuais.
insert into credit_contracts (contract_id, bank_id, amount, installments, accepted_at, terms)
select c.id, r.bank_id, r.credit_amount, r.installments, c.accepted_at,
 concat('CONTRATO DE CRÉDITO — Condições preservadas do contrato de aluguel: ', c.terms)
from contracts c join rentals r on r.id = c.rental_id
where r.bank_id is not null;
